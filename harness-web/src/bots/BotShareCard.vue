<script setup lang="ts">
import { ref } from 'vue'
import UiIcon from '../UiIcon.vue'
import BotLookAvatar from './BotLookAvatar.vue'
import { buildBotAvatarSvg, renderBotMarkdownContent, type BotCard, type BotEntry } from './api'

const props = defineProps<{
  card: BotCard
  entries: BotEntry[]
}>()

const emit = defineEmits<{
  close: []
}>()

const style = ref<'brand' | 'clean' | 'dark'>('brand')
const flash = ref('')

function setFlash(msg: string) {
  flash.value = msg
  window.setTimeout(() => {
    if (flash.value === msg) flash.value = ''
  }, 2000)
}

function wrapLines(ctx: CanvasRenderingContext2D, text: string, maxWidth: number): string[] {
  const lines: string[] = []
  for (const para of text.split(/\r?\n/)) {
    if (!para) { lines.push(''); continue }
    let line = ''
    for (const ch of para) {
      const test = line + ch
      if (ctx.measureText(test).width > maxWidth && line) {
        lines.push(line)
        line = ch
      } else {
        line = test
      }
    }
    if (line) lines.push(line)
  }
  return lines
}

async function loadAvatarImage(): Promise<HTMLImageElement | null> {
  try {
    const svg = buildBotAvatarSvg(props.card.bot.shape, props.card.bot.color)
    const blob = new Blob([svg], { type: 'image/svg+xml;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    try {
      const img = new Image()
      await new Promise<void>((resolve, reject) => {
        img.onload = () => resolve()
        img.onerror = () => reject(new Error('avatar load failed'))
        img.src = url
      })
      return img
    } finally {
      URL.revokeObjectURL(url)
    }
  } catch {
    return null
  }
}

async function buildCanvas(): Promise<HTMLCanvasElement> {
  const scale = 2
  const width = 560
  const padding = 32
  const innerWidth = width - padding * 2
  const temp = document.createElement('canvas').getContext('2d')!
  temp.font = '14px "Segoe UI", system-ui, sans-serif'

  const blocks = props.entries.map(entry => {
    const clean = renderBotMarkdownContent(entry.content).replace(/\*\*/g, '')
    const lines = wrapLines(temp, clean, innerWidth - 28)
    return { entry, lines, height: Math.max(46, lines.length * 22 + 34) }
  })

  const totalHeight = 104 + blocks.reduce((sum, b) => sum + b.height + 14, 0) + 46
  const canvas = document.createElement('canvas')
  canvas.width = width * scale
  canvas.height = totalHeight * scale
  const ctx = canvas.getContext('2d')!
  ctx.scale(scale, scale)

  const bg = style.value === 'dark' ? '#151a17' : style.value === 'clean' ? '#f7f9f7' : props.card.bot.color
  const cardBg = style.value === 'dark' ? '#202622' : '#ffffff'
  const textColor = style.value === 'dark' ? '#e8eee9' : '#1c251f'
  const mutedColor = style.value === 'dark' ? '#9eb0a3' : '#556259'
  const headText = style.value === 'brand' || style.value === 'dark' ? '#ffffff' : '#1c251f'

  ctx.fillStyle = bg
  ctx.fillRect(0, 0, width, totalHeight)

  const avatarImg = await loadAvatarImage()
  const titleX = avatarImg ? padding + 50 : padding
  if (avatarImg) {
    ctx.fillStyle = 'rgba(255,255,255,0.92)'
    ctx.beginPath()
    ctx.arc(padding + 20, 52, 21, 0, Math.PI * 2)
    ctx.fill()
    ctx.drawImage(avatarImg, padding + 1, 33, 38, 38)
  }

  ctx.fillStyle = headText
  ctx.font = 'bold 18px "Segoe UI", system-ui, sans-serif'
  ctx.fillText(`${props.card.bot.name} · Lv.${props.card.experience.level}`, titleX, 48)
  ctx.font = '12px "Segoe UI", system-ui, sans-serif'
  ctx.globalAlpha = 0.8
  ctx.fillText(props.card.bot.roleSummary || 'Java Harness Bot 团队对话分享', titleX, 68)
  ctx.globalAlpha = 1

  let y = 92
  for (const block of blocks) {
    const isUser = block.entry.kind === 'USER'
    ctx.fillStyle = isUser ? (style.value === 'dark' ? '#283f33' : '#e6f2ea') : cardBg
    ctx.beginPath()
    ctx.roundRect(padding, y, innerWidth, block.height, 12)
    ctx.fill()

    ctx.fillStyle = mutedColor
    ctx.font = 'bold 11px "Segoe UI", system-ui, sans-serif'
    ctx.fillText(isUser ? '我' : block.entry.kind === 'TASK_RESULT' ? '后台任务汇报' : props.card.bot.name, padding + 14, y + 20)

    ctx.fillStyle = textColor
    ctx.font = '14px "Segoe UI", system-ui, sans-serif'
    block.lines.forEach((line, idx) => {
      ctx.fillText(line, padding + 14, y + 42 + idx * 22)
    })
    y += block.height + 14
  }

  ctx.fillStyle = headText
  ctx.globalAlpha = 0.7
  ctx.font = '11px "Segoe UI", system-ui, sans-serif'
  ctx.fillText('Generated by Java Harness · Bot Workbench', padding, totalHeight - 18)
  return canvas
}

async function savePng() {
  const canvas = await buildCanvas()
  const link = document.createElement('a')
  link.download = `${props.card.bot.name}-share-${Date.now()}.png`
  link.href = canvas.toDataURL('image/png')
  link.click()
  setFlash('已保存 PNG')
}

async function copyImage() {
  try {
    const canvas = await buildCanvas()
    const blob = await new Promise<Blob | null>(resolve => canvas.toBlob(resolve, 'image/png'))
    if (blob && 'ClipboardItem' in window && navigator.clipboard?.write) {
      await navigator.clipboard.write([new ClipboardItem({ 'image/png': blob })])
      setFlash('已复制图片')
      return
    }
    const text = props.entries.map(e => `${e.kind === 'USER' ? '我' : props.card.bot.name}：${e.content}`).join('\n\n')
    await navigator.clipboard.writeText(text)
    setFlash('已复制文本')
  } catch {
    setFlash('复制失败，请点保存 PNG')
  }
}
</script>

<template>
  <div class="bot-modal-scrim" @click.self="emit('close')">
    <div class="bot-modal is-wide">
      <header>
        <h3>分享卡片预览（{{ entries.length }} 条消息）</h3>
        <button type="button" class="icon-button" @click="emit('close')"><UiIcon name="close" :size="16" /></button>
      </header>

      <div class="bot-share-styles">
        <button type="button" :class="{ active: style === 'brand' }" @click="style = 'brand'">Bot 主题色</button>
        <button type="button" :class="{ active: style === 'clean' }" @click="style = 'clean'">简洁浅色</button>
        <button type="button" :class="{ active: style === 'dark' }" @click="style = 'dark'">深色夜间</button>
      </div>

      <div
        class="bot-share-preview"
        :class="`is-${style}`"
        :style="style === 'brand' ? { background: card.bot.color } : undefined"
      >
        <div class="bot-share-head">
          <BotLookAvatar :shape="card.bot.shape" :color="card.bot.color" :size="30" />
          <div>
            <strong>{{ card.bot.name }} · Lv.{{ card.experience.level }}</strong>
            <small>{{ card.bot.roleSummary || 'Java Harness Bot' }}</small>
          </div>
        </div>
        <div class="bot-share-list">
          <div v-for="entry in entries" :key="entry.id" class="bot-share-item" :class="`is-${entry.kind.toLowerCase()}`">
            <small>{{ entry.kind === 'USER' ? '我' : entry.kind === 'TASK_RESULT' ? '后台任务汇报' : card.bot.name }}</small>
            <p>{{ renderBotMarkdownContent(entry.content).replace(/\*\*/g, '') }}</p>
          </div>
        </div>
      </div>

      <div class="bot-form-actions">
        <span v-if="flash" class="bot-flash-note">{{ flash }}</span>
        <button type="button" @click="copyImage">复制图片</button>
        <button type="button" class="is-primary" @click="savePng">保存 PNG</button>
      </div>
    </div>
  </div>
</template>
